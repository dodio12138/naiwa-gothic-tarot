/** 取某张牌当前语言的扩充语料 */
export function loreOf(id, en) {
  const L = LORE[id];
  if (!L) return null;
  const k = en ? 1 : 0;
  const pick = (o) => ({ love: o.love[k], work: o.work[k], advice: o.advice[k] });
  return {
    scene: L.scene[k], origin: L.origin[k], astro: L.astro[k],
    up: pick(L.up), rev: pick(L.rev),
    whispers: L.whispers.map((w) => w[k]),
  };
}
