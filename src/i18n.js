// 英文牌名用首字母大写形式（THE HIGH PRIESTESS → The High Priestess）
// 冠词、介词在名字中间保持小写（Wheel of Fortune）
export const titleCase = (s) => s.toLowerCase()
  .replace(/\b[a-z]+/g, (w, i) => (i > 0 && /^(of|the|and)$/.test(w) ? w : w[0].toUpperCase() + w.slice(1)));
