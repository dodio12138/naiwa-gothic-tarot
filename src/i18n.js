const KEY = 'naiwa-tarot-lang';
let lang = 'zh';
try {
  lang = localStorage.getItem(KEY) || ((navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en');
} catch { /* 无存储时用中文 */ }

export const getLang = () => lang;
export function setLang(v) {
  lang = v;
  try { localStorage.setItem(KEY, v); } catch { /* 忽略 */ }
}

